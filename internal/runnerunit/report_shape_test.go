// The Lab checkpoint reader re-encodes retained reports with this generated
// shape. Run with WAZA_UPDATE_REPORT_SHAPE=1 after changing a report type.
const browserReportShapePath = "../../web/src/api/runnerUnitReportShape.json"

type browserShapeField struct {
	Name      string `json:"name"`
	Type      string `json:"type"`
	OmitEmpty bool   `json:"omitempty,omitempty"`
}

type browserShapeType struct {
	Fields []browserShapeField `json:"fields"`
}

type browserShape struct {
	Comment string                      `json:"_comment"`
	Root    string                      `json:"root"`
	Structs map[string]browserShapeType `json:"structs"`
}

var (
	jsonMarshaler   = reflect.TypeFor[json.Marshaler]()
	jsonUnmarshaler = reflect.TypeFor[json.Unmarshaler]()
	textMarshaler   = reflect.TypeFor[encoding.TextMarshaler]()
	textUnmarshaler = reflect.TypeFor[encoding.TextUnmarshaler]()
)

func customJSON(kind reflect.Type) bool {
	for _, candidate := range []reflect.Type{kind, reflect.PointerTo(kind)} {
		if candidate.Implements(jsonMarshaler) || candidate.Implements(jsonUnmarshaler) ||
			candidate.Implements(textMarshaler) || candidate.Implements(textUnmarshaler) {
			return true
		}
	}
	return false
}

// shapeRef describes encoding/json's decode-then-encode behavior. Types it
// cannot reproduce exactly are "opaque", which the browser reports as unverified.
func shapeRef(kind reflect.Type, structs map[string]browserShapeType) (string, error) {
	if kind.Kind() == reflect.Pointer {
		elem, err := shapeRef(kind.Elem(), structs)
		return "ptr:" + elem, err
	}
	// RunResult's exact reader only fences key aliases and preserves numeric
	// tokens; its encoding is the default struct writer.
	if customJSON(kind) && kind != reflect.TypeFor[models.RunResult]() {
		return "opaque", nil
	}
	switch kind.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "bool", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return fmt.Sprintf("int%d", kind.Bits()), nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return fmt.Sprintf("uint%d", kind.Bits()), nil
	case reflect.Float64:
		return "float64", nil
	case reflect.Interface:
		if kind.NumMethod() == 0 {
			return "any", nil
		}
		return "opaque", nil
	case reflect.Slice:
		if kind.Elem().Kind() == reflect.Uint8 {
			return "opaque", nil
		}
		elem, err := shapeRef(kind.Elem(), structs)
		return "slice:" + elem, err
	case reflect.Map:
		if kind.Key().Kind() != reflect.String || customJSON(kind.Key()) {
			return "opaque", nil
		}
		elem, err := shapeRef(kind.Elem(), structs)
		return "map:" + elem, err
	case reflect.Struct:
		name := path.Base(kind.PkgPath()) + "." + kind.Name()
		if _, seen := structs[name]; seen {
			return name, nil
		}
		structs[name] = browserShapeType{}
		var fields []browserShapeField
		for i := range kind.NumField() {
			field := kind.Field(i)
			if field.Anonymous {
				delete(structs, name)
				return "opaque", nil
			}
			if !field.IsExported() {
				continue
			}
			tag := field.Tag.Get("json")
			if tag == "-" {
				continue
			}
			tagName, options, _ := strings.Cut(tag, ",")
			if !plainJSONName(tagName) || strings.Contains(","+options+",", ",string,") ||
				strings.Contains(","+options+",", ",omitzero,") {
				delete(structs, name)
				return "opaque", nil
			}
			ref, err := shapeRef(field.Type, structs)
			if err != nil {
				return "", err
			}
			fields = append(fields, browserShapeField{
				Name: tagName, Type: ref, OmitEmpty: strings.Contains(","+options+",", ",omitempty,"),
			})
		}
		structs[name] = browserShapeType{Fields: fields}
		return name, nil
	default:
		return "opaque", nil
	}
}

// plainJSONName keeps the browser writer to explicit ASCII keys that need no escaping.
func plainJSONName(name string) bool {
	if name == "" {
		return false
	}
	for _, character := range name {
		if !(character == '_' || character == '-' || character >= 'a' && character <= 'z' ||
			character >= 'A' && character <= 'Z' || character >= '0' && character <= '9') {
			return false
		}
	}
	return true
}

func generateBrowserReportShape() ([]byte, error) {
	shape := browserShape{
		Comment: "Generated by internal/runnerunit/report_shape_test.go; do not edit.",
		Structs: map[string]browserShapeType{},
	}
	root, err := shapeRef(reflect.TypeFor[Report](), shape.Structs)
	if err != nil {
		return nil, err
	}
	shape.Root = root
	data, err := json.MarshalIndent(shape, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

func TestBrowserReportShapeIsCurrent(t *testing.T) {
	generated, err := generateBrowserReportShape()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("WAZA_UPDATE_REPORT_SHAPE") == "1" {
		if err := os.WriteFile(browserReportShapePath, generated, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	current, err := os.ReadFile(browserReportShapePath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(bytes.ReplaceAll(current, []byte("\r\n"), []byte("\n")), generated) {
		t.Fatalf("%s is stale; rerun with WAZA_UPDATE_REPORT_SHAPE=1", browserReportShapePath)
	}
}
